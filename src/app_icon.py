def app_icon():
    pm = QPixmap()
    pm.loadFromData(base64.b64decode(_PNG_B64), "PNG")
    return QIcon(pm)


def apply_app_icon(app):
    """Icone de fenetre + identifiant d'application (barre des taches, dock)."""
    try:
        icon = app_icon()
        if not icon.isNull():
            app.setWindowIcon(icon)
        if sys.platform.startswith("win"):
            import ctypes
            ctypes.windll.shell32.SetCurrentProcessExplicitAppUserModelID("VinaStudio.VinaStudio.1")
        else:
            app.setDesktopFileName("vinastudio")
    except Exception as exc:
        print("[ICONE] non appliquee :", exc)
